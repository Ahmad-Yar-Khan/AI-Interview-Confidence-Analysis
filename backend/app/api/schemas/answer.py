"""
answer.py (schemas)
--------------------
Pydantic request/response models for the answer-scoring route.
Pulled out of main.py so route files don't need to redefine or import schemas
from the app factory module.
"""

from pydantic import BaseModel, Field


class AnswerPayload(BaseModel):
    session_id: str
    question_id: str
    question_text: str
    model_answer: str | None = None
    user_answer: str
    category: str
    difficulty: str
    has_answer: bool = True
    # Frontend queue facts, used to enforce the interview question cap.
    queue_length: int | None = None
    question_position: int | None = None


class ScoreResponse(BaseModel):
    question_id: str
    overall: int
    is_behavioral: bool
    angles: dict
    model_answer: str | None
    feedback: str = ""
    evaluation_score: int | None = None
    evaluation_improvements: list[str] = Field(default_factory=list)
    criteria: dict = Field(default_factory=dict)
    # Generated by the evaluation flow when the score is below 6 and this
    # question has fewer than two follow-ups.
    followup: dict | None = None
